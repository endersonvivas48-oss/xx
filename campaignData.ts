export function calculateGladiatorDuelRewards(handicap: GladiatorDuelHandicap) {
  const mult = GLADIATOR_DUEL_HANDICAPS[handicap]?.rewardMult ?? 1.0;
  return {
    gold: Math.round(GLADIATOR_DUEL_BASE_REWARDS.gold * mult),
    exp: Math.round(GLADIATOR_DUEL_BASE_REWARDS.exp * mult),
    score: Math.round(GLADIATOR_DUEL_BASE_REWARDS.score * mult),
    mult,
  };
}

